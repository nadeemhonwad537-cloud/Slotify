-- Slotify migration 002: retain source workload rows separately from confirmed master data.
-- Source columns are immutable after ingestion; only resolution fields may be reviewed.
CREATE TABLE workload_import_batches (
  batch_id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  source_key VARCHAR(120) NOT NULL,
  content_sha256 CHAR(64) NOT NULL,
  source_document_id BIGINT UNSIGNED NOT NULL,
  status ENUM('REVIEW_REQUIRED','PARTIALLY_RESOLVED','RESOLVED') NOT NULL DEFAULT 'REVIEW_REQUIRED',
  imported_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  UNIQUE KEY uq_workload_import_source (source_key),
  CONSTRAINT fk_wib_document FOREIGN KEY (source_document_id) REFERENCES source_documents(document_id)
) ENGINE=InnoDB;
-- @@
CREATE TABLE workload_import_rows (
  workload_import_row_id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  batch_id BIGINT UNSIGNED NOT NULL,
  source_row_number SMALLINT UNSIGNED NOT NULL,
  source_page TINYINT UNSIGNED NOT NULL,
  raw_source_line TEXT NOT NULL,
  source_name VARCHAR(255) NULL,
  group_label VARCHAR(80) NOT NULL,
  faculty_category ENUM('REGULAR_CANDIDATE','GUEST','TA','UNKNOWN') NOT NULL,
  subjects JSON NOT NULL,
  lab_duty JSON NOT NULL,
  sdp_hours DECIMAL(5,2) NULL,
  minor_project_hours DECIMAL(5,2) NULL,
  printed_theory_hours DECIMAL(5,2) NULL,
  printed_lab_hours DECIMAL(5,2) NULL,
  printed_total_hours DECIMAL(5,2) NULL,
  printed_load_source_text VARCHAR(255) NOT NULL,
  source_snapshot JSON NOT NULL,
  unresolved_fields JSON NOT NULL,
  issues JSON NOT NULL,
  resolution_status ENUM('UNRESOLVED','REVIEWED','RESOLVED','SKIPPED') NOT NULL DEFAULT 'UNRESOLVED',
  faculty_id BIGINT UNSIGNED NULL,
  department_id INT UNSIGNED NULL,
  term_id INT UNSIGNED NULL,
  resolution_json JSON NULL,
  review_notes TEXT NULL,
  reviewed_by BIGINT UNSIGNED NULL,
  reviewed_at DATETIME NULL,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  UNIQUE KEY uq_workload_source_row (batch_id, source_row_number),
  KEY ix_workload_import_faculty (faculty_id, resolution_status),
  KEY ix_workload_import_status (batch_id, resolution_status),
  CONSTRAINT fk_wir_batch FOREIGN KEY (batch_id) REFERENCES workload_import_batches(batch_id),
  CONSTRAINT fk_wir_faculty FOREIGN KEY (faculty_id) REFERENCES faculty_profiles(faculty_id),
  CONSTRAINT fk_wir_department FOREIGN KEY (department_id) REFERENCES departments(dept_id),
  CONSTRAINT fk_wir_term FOREIGN KEY (term_id) REFERENCES terms(term_id),
  CONSTRAINT fk_wir_reviewer FOREIGN KEY (reviewed_by) REFERENCES users(user_id),
  CONSTRAINT ck_wir_page CHECK (source_page IN (1, 2)),
  CONSTRAINT ck_wir_row CHECK (source_row_number BETWEEN 1 AND 39),
  CONSTRAINT ck_wir_reviewed CHECK (resolution_status <> 'RESOLVED' OR (reviewed_by IS NOT NULL AND reviewed_at IS NOT NULL))
) ENGINE=InnoDB;
